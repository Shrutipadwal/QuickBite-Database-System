-- =========================================
-- VIEWS
-- =========================================

-- View for active orders

CREATE VIEW active_orders_view AS
SELECT
    order_id,
    customer_id,
    order_status,
    total_amount
FROM orders
WHERE order_status IN ('Pending', 'Out for Delivery');


-- View for restaurant revenue

CREATE VIEW restaurant_revenue_view AS
SELECT
    r.restaurant_name,
    SUM(oi.subtotal) AS total_revenue
FROM restaurants r
INNER JOIN menu_items m
ON r.restaurant_id = m.restaurant_id
INNER JOIN order_items oi
ON m.item_id = oi.item_id
GROUP BY r.restaurant_name;


-- View for customer order history

CREATE VIEW customer_order_history_view AS
SELECT
    c.name AS customer_name,
    o.order_id,
    o.order_status,
    o.total_amount
FROM customers c
INNER JOIN orders o
ON c.customer_id = o.customer_id;


