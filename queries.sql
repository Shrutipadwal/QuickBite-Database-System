-- Display all customers

SELECT * FROM customers;


-- Show all available food items

SELECT item_name, price, category
FROM menu_items
WHERE availability_status = 'Available';


-- Restaurants with high ratings

SELECT restaurant_name, location, rating
FROM restaurants
WHERE rating > 4.2;


-- Orders sorted by total amount

SELECT order_id, total_amount, order_status
FROM orders
ORDER BY total_amount DESC;


-- Top 3 expensive food items

SELECT item_name, price
FROM menu_items
ORDER BY price DESC
LIMIT 3;


-- Customers located in Pune

SELECT name, email, address
FROM customers
WHERE address = 'Pune';


-- Display delivered orders

SELECT order_id, order_status, total_amount
FROM orders
WHERE order_status = 'Delivered';


-- Food items within price range

SELECT item_name, price
FROM menu_items
WHERE price BETWEEN 100 AND 300;


-- Restaurants starting with letter S

SELECT restaurant_name
FROM restaurants
WHERE restaurant_name LIKE 'S%';


-- Display all food categories

SELECT DISTINCT category
FROM menu_items;


-- =========================================
-- JOIN QUERIES
-- =========================================

-- Customers and their orders

SELECT
    c.customer_id,
    c.name,
    o.order_id,
    o.order_status,
    o.total_amount
FROM customers c
INNER JOIN orders o
ON c.customer_id = o.customer_id;


-- Restaurants with their food items

SELECT
    r.restaurant_name,
    m.item_name,
    m.price,
    m.category
FROM restaurants r
INNER JOIN menu_items m
ON r.restaurant_id = m.restaurant_id;


-- Orders and payment information

SELECT
    o.order_id,
    o.total_amount,
    p.payment_method,
    p.payment_status
FROM orders o
INNER JOIN payments p
ON o.order_id = p.order_id;


-- Orders with delivery partner details

SELECT
    o.order_id,
    o.order_status,
    d.partner_name,
    d.vehicle_type
FROM orders o
INNER JOIN delivery_partners d
ON o.delivery_partner_id = d.partner_id;


-- Customer reviews for restaurants

SELECT
    c.name AS customer_name,
    r.restaurant_name,
    rv.rating,
    rv.comment
FROM reviews rv
INNER JOIN customers c
ON rv.customer_id = c.customer_id
INNER JOIN restaurants r
ON rv.restaurant_id = r.restaurant_id;


-- Complete order details

SELECT
    o.order_id,
    c.name AS customer_name,
    r.restaurant_name,
    m.item_name,
    oi.quantity,
    oi.subtotal
FROM order_items oi
INNER JOIN orders o
ON oi.order_id = o.order_id
INNER JOIN customers c
ON o.customer_id = c.customer_id
INNER JOIN menu_items m
ON oi.item_id = m.item_id
INNER JOIN restaurants r
ON m.restaurant_id = r.restaurant_id;


