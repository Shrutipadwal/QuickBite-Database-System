-- =========================================
-- AGGREGATE FUNCTIONS + GROUP BY + HAVING
-- =========================================

-- Total number of customers

SELECT COUNT(*) AS total_customers
FROM customers;


-- Total revenue from all delivered orders

SELECT SUM(total_amount) AS total_revenue
FROM orders
WHERE order_status = 'Delivered';


-- Average restaurant rating

SELECT AVG(rating) AS average_rating
FROM restaurants;


-- Most expensive menu item

SELECT item_name, price
FROM menu_items
WHERE price = (
    SELECT MAX(price)
    FROM menu_items
);


-- Number of orders placed by each customer

SELECT
    c.name,
    COUNT(o.order_id) AS total_orders
FROM customers c
INNER JOIN orders o
ON c.customer_id = o.customer_id
GROUP BY c.name;


-- Revenue generated by each restaurant

SELECT
    r.restaurant_name,
    SUM(oi.subtotal) AS total_revenue
FROM restaurants r
INNER JOIN menu_items m
ON r.restaurant_id = m.restaurant_id
INNER JOIN order_items oi
ON m.item_id = oi.item_id
GROUP BY r.restaurant_name;


-- Most ordered menu items

SELECT
    m.item_name,
    SUM(oi.quantity) AS total_quantity_ordered
FROM menu_items m
INNER JOIN order_items oi
ON m.item_id = oi.item_id
GROUP BY m.item_name
ORDER BY total_quantity_ordered DESC;


-- Restaurants with high average ratings

SELECT
    restaurant_name,
    rating
FROM restaurants
WHERE rating > 4.3;


-- Number of orders by status

SELECT
    order_status,
    COUNT(*) AS total_orders
FROM orders
GROUP BY order_status;


-- Customers with multiple orders

SELECT
    c.name,
    COUNT(o.order_id) AS total_orders
FROM customers c
INNER JOIN orders o
ON c.customer_id = o.customer_id
GROUP BY c.name
HAVING COUNT(o.order_id) > 1;


-- =========================================
-- SUBQUERIES
-- =========================================

-- Most expensive food item

SELECT item_name, price
FROM menu_items
WHERE price = (
    SELECT MAX(price)
    FROM menu_items
);


-- Customers with order amount above average

SELECT order_id, customer_id, total_amount
FROM orders
WHERE total_amount > (
    SELECT AVG(total_amount)
    FROM orders
);


-- Restaurant with highest rating

SELECT restaurant_name, rating
FROM restaurants
WHERE rating = (
    SELECT MAX(rating)
    FROM restaurants
);


-- Orders above average total amount

SELECT order_id, total_amount
FROM orders
WHERE total_amount > (
    SELECT AVG(total_amount)
    FROM orders
);


-- Customer with maximum number of orders

SELECT customer_id, COUNT(order_id) AS total_orders
FROM orders
GROUP BY customer_id
HAVING COUNT(order_id) = (
    SELECT MAX(order_count)
    FROM (
        SELECT COUNT(order_id) AS order_count
        FROM orders
        GROUP BY customer_id
    ) AS temp
);


