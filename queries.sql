DELIMITER //

CREATE PROCEDURE GetOrdersByStatus(
    IN input_status VARCHAR(30)
)
BEGIN

    SELECT
        order_id,
        customer_id,
        order_status,
        total_amount
    FROM orders
    WHERE order_status = input_status;

END //

DELIMITER ;


DELIMITER //

CREATE PROCEDURE GetRestaurantMenu(
    IN input_restaurant_id INT
)
BEGIN

    SELECT
        item_name,
        price,
        category
    FROM menu_items
    WHERE restaurant_id = input_restaurant_id;

END //

DELIMITER ;


-- =========================================
-- TRIGGERS
-- =========================================

DELIMITER //

CREATE TRIGGER update_order_total
AFTER INSERT ON order_items
FOR EACH ROW
BEGIN

    UPDATE orders
    SET total_amount = (
        SELECT SUM(subtotal)
        FROM order_items
        WHERE order_id = NEW.order_id
    )
    WHERE order_id = NEW.order_id;

END //

DELIMITER ;


